// Helper function to get a prophet by ID
export const getProphetById = (id: string): Prophet | undefined => {
  return PROPHETS.find((prophet) => prophet.id === id);
};

// Helper function to get prophets by order range
export const getProphetsByOrderRange = (start: number, end: number): Prophet[] => {
  return PROPHETS.filter((prophet) => prophet.order >= start && prophet.order <= end);
};

